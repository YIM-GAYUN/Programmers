import sys
input = sys.stdin.readline

N, M = map(int, input().split())
p = [list(map(int, input().split())) for _ in range(N)]

# 19개 shape
shapes = [
    # I (2)
    [(0,0),(0,1),(0,2),(0,3)],
    [(0,0),(1,0),(2,0),(3,0)],
    # O (1)
    [(0,0),(0,1),(1,0),(1,1)],
    # L/J (8)
    [(0,0),(1,0),(2,0),(2,1)],
    [(0,1),(1,1),(2,1),(2,0)],
    [(0,0),(0,1),(1,0),(2,0)],
    [(0,0),(0,1),(1,1),(2,1)],
    [(0,0),(0,1),(0,2),(1,0)],
    [(0,0),(0,1),(0,2),(1,2)],
    [(0,0),(1,0),(1,1),(1,2)],
    [(0,2),(1,0),(1,1),(1,2)],
    # S/Z (4)
    [(0,0),(0,1),(1,1),(1,2)],
    [(0,1),(0,2),(1,0),(1,1)],
    [(0,0),(1,0),(1,1),(2,1)],
    [(0,1),(1,1),(1,0),(2,0)],
    # T (4)
    [(0,0),(0,1),(0,2),(1,1)],
    [(0,1),(1,0),(1,1),(2,1)],
    [(1,0),(1,1),(1,2),(0,1)],
    [(0,0),(1,0),(1,1),(2,0)],
]

ans = 0
for i in range(N):
    for j in range(M):
        for shape in shapes:
            s = 0
            ok = True
            for di, dj in shape:
                ni, nj = i + di, j + dj
                if 0 <= ni < N and 0 <= nj < M:
                    s += p[ni][nj]
                else:
                    ok = False
                    break
            if ok and s > ans:
                ans = s

print(ans)